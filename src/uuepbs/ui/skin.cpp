        // A file name from skin.json must stay inside the skin's folder.
        bool safe_relative(const std::string& file)
        {
            // Checked the same way on every OS: no drive letters or streams (':'), no leading
            // slash, no ".." part, with either kind of slash.
            if (file.empty() || file.find(':') != std::string::npos || file[0] == '/' || file[0] == '\\')
            {
                return false;
            }
            std::string unified = file;
            std::replace(unified.begin(), unified.end(), '\\', '/');
            size_t start = 0;
            while (start <= unified.size())
            {
                const size_t end = std::min(unified.find('/', start), unified.size());
                if (unified.compare(start, end - start, "..") == 0)
                {
                    return false;
                }
                start = end + 1;
            }
            const fs::path p = path_from_utf8(file);
            if (p.empty() || p.is_absolute() || p.has_root_name() || p.has_root_directory())
            {
                return false;
            }
            for (const fs::path& part : p.lexically_normal())
            {
                if (part == "..")
                {
                    return false;
                }
            }
            return true;
        }

        ImTextureData* make_texture(const Rgba8Image& img)
        {
            auto* tex = IM_NEW(ImTextureData)();
            tex->Create(ImTextureFormat_RGBA32, img.width, img.height);
            std::memcpy(tex->Pixels, img.pixels.data(), img.pixels.size());
            tex->UseColors = true;
            tex->RefCount = 1;
            tex->UsedRect = {0, 0, static_cast<unsigned short>(img.width), static_cast<unsigned short>(img.height)};
            tex->SetStatus(ImTextureStatus_WantCreate); // a fresh ImTextureData starts as "OK"
            ImGui::RegisterUserTexture(tex);
            return tex;
        }

