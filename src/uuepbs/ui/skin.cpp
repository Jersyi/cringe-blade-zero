        int hex_digit(char c)
        {
            if (c >= '0' && c <= '9')
                return c - '0';
            if (c >= 'a' && c <= 'f')
                return c - 'a' + 10;
            if (c >= 'A' && c <= 'F')
                return c - 'A' + 10;
            return -1;
        }

        bool color_of(const JsonValue& v, ImVec4& out)
        {
            if (v.kind == JsonValue::Kind::String)
            {
                return parse_color(v.text, out);
            }
            if (v.kind == JsonValue::Kind::Array && (v.items.size() == 3 || v.items.size() == 4))
            {
                float c[4] = {0, 0, 0, 1};
                bool any_big = false;
                for (size_t i = 0; i < v.items.size(); ++i)
                {
                    if (v.items[i].kind != JsonValue::Kind::Number)
                    {
                        return false;
                    }
                    c[i] = static_cast<float>(v.items[i].number);
                    any_big = any_big || c[i] > 1.0f;
                }
                for (int i = 0; i < 4; ++i)
                {
                    if (any_big && (i < 3 || v.items.size() == 4)) // 0..255 notation
                    {
                        c[i] = (i == 3 && v.items.size() == 3) ? 1.0f : c[i] / 255.0f;
                    }
                    c[i] = std::clamp(c[i], 0.0f, 1.0f);
                }
                out = ImVec4(c[0], c[1], c[2], c[3]);
                return true;
            }
            return false;
        }

        bool image_of(const JsonValue& v, SkinImageSpec& out, std::string& why)
        {
            if (v.kind == JsonValue::Kind::String)
            {
                out.file = v.text;
                return !out.file.empty();
            }
            if (v.kind != JsonValue::Kind::Object)
            {
                why = "must be a file name or { \"file\": ... }";
                return false;
            }
            const JsonValue* f = v.find("file");
            if (!f || f->kind != JsonValue::Kind::String || f->text.empty())
            {
                why = "has no \"file\"";
                return false;
            }
            out.file = f->text;
            if (const JsonValue* m = v.find("mode"); m && m->kind == JsonValue::Kind::String)
            {
                const std::string mode = lower(m->text);
                static const std::pair<const char*, ImageMode> modes[] = {{"stretch", ImageMode::Stretch}, {"cover", ImageMode::Cover},
                                                                          {"contain", ImageMode::Contain}, {"fit", ImageMode::Contain},
                                                                          {"center", ImageMode::Center},   {"centre", ImageMode::Center},
                                                                          {"tile", ImageMode::Tile},       {"nine", ImageMode::Nine},
                                                                          {"nine-slice", ImageMode::Nine}, {"9slice", ImageMode::Nine}};
                bool found = false;
                for (const auto& [name, mode_value] : modes)
                {
                    if (mode == name)
                    {
                        out.mode = mode_value;
                        out.has_mode = found = true;
                    }
                }
                if (!found)
                {
                    why = "unknown mode \"" + m->text + "\" (stretch, cover, contain, center, tile or nine)";
                    return false;
                }
            }
            if (const JsonValue* s = v.find("slice"))
            {
                if (s->kind == JsonValue::Kind::Number)
                {
                    out.slice[0] = out.slice[1] = out.slice[2] = out.slice[3] = static_cast<float>(std::max(0.0, s->number));
                }
                else if (s->kind == JsonValue::Kind::Array && (s->items.size() == 4 || s->items.size() == 2))
                {
                    for (size_t i = 0; i < 4; ++i)
                    {
                        const JsonValue& item = s->items[s->items.size() == 2 ? i % 2 : i];
                        out.slice[i] = item.kind == JsonValue::Kind::Number ? static_cast<float>(std::max(0.0, item.number)) : 0.0f;
                    }
                }
                if (!out.has_mode)
                {
                    out.mode = ImageMode::Nine;
                    out.has_mode = true;
                }
            }
            if (const JsonValue* t = v.find("tint"))
            {
                if (!color_of(*t, out.tint))
                {
                    why = "has an unreadable \"tint\"";
                    return false;
                }
            }
            if (const JsonValue* sc = v.find("scale"); sc && sc->kind == JsonValue::Kind::Number && sc->number > 0.01)
            {
                out.scale = static_cast<float>(std::min(sc->number, 16.0));
            }
            return true;
        }

