    void Skin::draw(ImDrawList* dl, const Image& img, ImVec2 a, ImVec2 b, float alpha) const
    {
        if (!img.tex || img.width <= 0 || img.height <= 0 || b.x <= a.x || b.y <= a.y)
        {
            return;
        }
        const ImTextureRef ref = img.tex->GetTexRef();
        const ImU32 col = tint_color(img.spec.tint, alpha * ImGui::GetStyle().Alpha);
        const float W = b.x - a.x, H = b.y - a.y;
        const float iw = static_cast<float>(img.width), ih = static_cast<float>(img.height);
        switch (img.spec.mode)
        {
        case ImageMode::Stretch:
            dl->AddImage(ref, a, b, ImVec2(0, 0), ImVec2(1, 1), col);
            break;
        case ImageMode::Cover: {
            const float s = std::max(W / iw, H / ih);
            const float uw = W / (iw * s), vh = H / (ih * s);
            dl->AddImage(ref, a, b, ImVec2((1.0f - uw) * 0.5f, (1.0f - vh) * 0.5f), ImVec2((1.0f + uw) * 0.5f, (1.0f + vh) * 0.5f), col);
            break;
        }
        case ImageMode::Contain: {
            const float s = std::min(W / iw, H / ih);
            const ImVec2 size(iw * s, ih * s);
            const ImVec2 p(snap(a.x + (W - size.x) * 0.5f), snap(a.y + (H - size.y) * 0.5f));
            dl->AddImage(ref, p, ImVec2(p.x + snap(size.x), p.y + snap(size.y)), ImVec2(0, 0), ImVec2(1, 1), col);
            break;
        }
        case ImageMode::Center: {
            const float s = img.spec.scale * m_dpi;
            const ImVec2 size(snap(iw * s), snap(ih * s));
            const ImVec2 p(snap(a.x + (W - size.x) * 0.5f), snap(a.y + (H - size.y) * 0.5f));
            dl->PushClipRect(a, b, true);
            dl->AddImage(ref, p, ImVec2(p.x + size.x, p.y + size.y), ImVec2(0, 0), ImVec2(1, 1), col);
            dl->PopClipRect();
            break;
        }
        case ImageMode::Tile: {
            const float s = img.spec.scale * m_dpi;
            const float tw = std::max(4.0f, snap(iw * s)), th = std::max(4.0f, snap(ih * s));
            const int nx = static_cast<int>(std::ceil(W / tw)), ny = static_cast<int>(std::ceil(H / th));
            if (nx * ny > 2500)
            {
                dl->AddImage(ref, a, b, ImVec2(0, 0), ImVec2(W / tw, H / th), col); // falls back to one stretched quad
                break;
            }
            dl->PushClipRect(a, b, true);
            for (int y = 0; y < ny; ++y)
            {
                for (int x = 0; x < nx; ++x)
                {
                    const ImVec2 p(snap(a.x) + tw * static_cast<float>(x), snap(a.y) + th * static_cast<float>(y));
                    dl->AddImage(ref, p, ImVec2(p.x + tw, p.y + th), ImVec2(0, 0), ImVec2(1, 1), col);
                }
            }
            dl->PopClipRect();
            break;
        }
        case ImageMode::Nine: {
            const float s = img.spec.scale * m_dpi;
            float l = img.spec.slice[0] * s, t = img.spec.slice[1] * s, r = img.spec.slice[2] * s, bt = img.spec.slice[3] * s;
            // Borders shrink together when the area is smaller than they are.
            if (l + r > W && l + r > 0.0f)
            {
                const float k = W / (l + r);
                l *= k, r *= k;
            }
            if (t + bt > H && t + bt > 0.0f)
            {
                const float k = H / (t + bt);
                t *= k, bt *= k;
            }
            const float x[4] = {snap(a.x), snap(a.x + l), snap(b.x - r), snap(b.x)};
            const float y[4] = {snap(a.y), snap(a.y + t), snap(b.y - bt), snap(b.y)};
            const float u[4] = {0.0f, img.spec.slice[0] / iw, 1.0f - img.spec.slice[2] / iw, 1.0f};
            const float v[4] = {0.0f, img.spec.slice[1] / ih, 1.0f - img.spec.slice[3] / ih, 1.0f};
            for (int j = 0; j < 3; ++j)
            {
                for (int i = 0; i < 3; ++i)
                {
                    if (x[i + 1] > x[i] && y[j + 1] > y[j] && u[i + 1] > u[i] && v[j + 1] > v[j])
                    {
                        dl->AddImage(ref, ImVec2(x[i], y[j]), ImVec2(x[i + 1], y[j + 1]), ImVec2(u[i], v[j]), ImVec2(u[i + 1], v[j + 1]), col);
                    }
                }
            }
            break;
        }
        }
    }

    // Splits the current window's draw list so an image can be drawn *under* the next widget
    // after the widget has been laid out (its rectangle and hover state are known then).
    // Never nested: each helper uses it around exactly one widget.
    class Skin::Underlay
    {
      public:
        Underlay(Skin& skin, bool active) : m_skin(skin), m_active(active)
        {
            if (m_active)
            {
                m_dl = ImGui::GetWindowDrawList();
                m_skin.m_split.Split(m_dl, 2);
                m_skin.m_split.SetCurrentChannel(m_dl, 1);
            }
        }
        ImDrawList* back()
        {
            m_skin.m_split.SetCurrentChannel(m_dl, 0);
            return m_dl;
        }
        void finish()
        {
            if (m_active)
            {
                m_skin.m_split.Merge(m_dl);
                m_active = false;
            }
        }
        ~Underlay() { finish(); }

      private:
        Skin& m_skin;
        bool m_active;
        ImDrawList* m_dl{};
    };

    void Skin::draw_window_background()
    {
        if (const Image* img = find("background"))
        {
            const ImVec2 p = ImGui::GetWindowPos(), s = ImGui::GetWindowSize();
            draw(ImGui::GetWindowDrawList(), *img, p, ImVec2(p.x + s.x, p.y + s.y), 1.0f);
        }
    }

    void Skin::draw_header_strip(float row_height)
    {
        if (const Image* img = find("header"))
        {
            if (find("logo")) // the title row is as tall as the logo
            {
                const auto lh = m_spec.style.find("logo_height");
                row_height = std::max(row_height, snap(ImGui::GetFontSize() * (lh != m_spec.style.end() ? std::clamp(lh->second.x, 0.5f, 6.0f) : 1.6f)));
            }
            const ImVec2 wp = ImGui::GetWindowPos();
            const float bottom = ImGui::GetCursorScreenPos().y + row_height + ImGui::GetStyle().ItemSpacing.y * 0.5f;
            draw(ImGui::GetWindowDrawList(), *img, wp, ImVec2(wp.x + ImGui::GetWindowWidth(), snap(bottom)), 1.0f);
        }
    }

    bool Skin::logo(float height)
    {
        const Image* img = find("logo");
        if (!img)
        {
            return false;
        }
        const auto lh = m_spec.style.find("logo_height");
        const float h = snap(height * (lh != m_spec.style.end() ? std::clamp(lh->second.x, 0.5f, 6.0f) : 1.6f));
        const float w = std::min(snap(h * static_cast<float>(img->width) / static_cast<float>(img->height)), ImGui::GetContentRegionAvail().x * 0.6f);
        const ImVec2 p = ImGui::GetCursorScreenPos();
        draw(ImGui::GetWindowDrawList(), *img, p, ImVec2(p.x + w, p.y + h), 1.0f);
        ImGui::Dummy(ImVec2(w, h));
        return true;
    }

    bool Skin::icon(std::string_view key, float size)
    {
        if (key.empty())
        {
            return false;
        }
        const Image* img = find("icon." + lower(key));
        if (!img)
        {
            return false;
        }
        const ImVec2 p = ImGui::GetCursorScreenPos();
        const float frame = ImGui::GetFrameHeight();
        const float y = p.y + std::max(0.0f, (frame - size) * 0.5f);
        draw(ImGui::GetWindowDrawList(), *img, ImVec2(p.x, y), ImVec2(p.x + size, y + size), 1.0f);
        ImGui::Dummy(ImVec2(size, std::min(size, frame)));
        ImGui::SameLine();
        return true;
    }

    namespace
    {
        // Leading spaces that leave room for an icon inside a button or tab label.
        std::string with_icon_room(const char* label, float icon_w)
        {
            const float space = std::max(1.0f, ImGui::CalcTextSize(" ").x);
            const int n = static_cast<int>(std::ceil(icon_w / space));
            return std::string(static_cast<size_t>(n), ' ') + label;
        }

        bool visible_text(const char* label)
        {
            return label && label[0] && !(label[0] == '#' && label[1] == '#');
        }

        void push_clear(std::initializer_list<ImGuiCol> cols)
        {
            for (ImGuiCol c : cols)
            {
                ImGui::PushStyleColor(c, ImVec4(0, 0, 0, 0));
            }
        }
    } // namespace

    bool Skin::button(const char* label, std::string_view icon_key, const ImVec2& size)
    {
        const Image* normal = find("button");
        const Image* ic = icon_key.empty() ? nullptr : find("icon." + lower(icon_key));
        const float icon_w = ImGui::GetFontSize();
        std::string padded;
        const char* text = label;
        ImVec2 sz = size;
        if (ic)
        {
            if (visible_text(label))
            {
                padded = with_icon_room(label, icon_w + ImGui::GetStyle().ItemInnerSpacing.x * 0.5f);
                text = padded.c_str();
            }
            else if (sz.x <= 0.0f)
            {
                sz = ImVec2(icon_w + ImGui::GetStyle().FramePadding.x * 2.0f, 0.0f);
            }
        }
        bool pressed = false;
        {
            Underlay under(*this, normal != nullptr);
            if (normal)
            {
                push_clear({ImGuiCol_Button, ImGuiCol_ButtonHovered, ImGuiCol_ButtonActive});
            }
            pressed = ImGui::Button(text, sz);
            if (normal)
            {
                ImGui::PopStyleColor(3);
                const Image* img = normal;
                if (ImGui::IsItemActive() && find("button_active"))
                {
                    img = find("button_active");
                }
                else if (ImGui::IsItemHovered() && find("button_hover"))
                {
                    img = find("button_hover");
                }
                draw(under.back(), *img, ImGui::GetItemRectMin(), ImGui::GetItemRectMax(), 1.0f);
            }
        }
        if (ic)
        {
            const ImVec2 a = ImGui::GetItemRectMin(), b = ImGui::GetItemRectMax();
            const float h = b.y - a.y;
            const float x = visible_text(label) ? a.x + ImGui::GetStyle().FramePadding.x : a.x + (b.x - a.x - icon_w) * 0.5f;
            const float y = a.y + (h - icon_w) * 0.5f;
            draw(ImGui::GetWindowDrawList(), *ic, ImVec2(snap(x), snap(y)), ImVec2(snap(x) + icon_w, snap(y) + icon_w), 1.0f);
        }
        return pressed;
    }

    float Skin::button_width(const char* label, std::string_view icon_key) const
    {
        const ImGuiStyle& style = ImGui::GetStyle();
        const bool ic = !icon_key.empty() && find("icon." + lower(icon_key)) != nullptr;
        if (ic && !visible_text(label))
        {
            return ImGui::GetFontSize() + style.FramePadding.x * 2.0f;
        }
        const char* shown = label;
        std::string padded;
        if (ic)
        {
            padded = with_icon_room(label, ImGui::GetFontSize() + style.ItemInnerSpacing.x * 0.5f);
            shown = padded.c_str();
        }
        return ImGui::CalcTextSize(shown, nullptr, true).x + style.FramePadding.x * 2.0f;
    }

