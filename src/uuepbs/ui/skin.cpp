    std::string Skin::remembered() const
    {
        if (!m_folder_ready)
        {
            return {};
        }
        std::ifstream in(m_folder / "_selected.txt", std::ios::binary);
        std::string line;
        if (in && std::getline(in, line))
        {
            while (!line.empty() && (line.back() == '\r' || line.back() == ' '))
            {
                line.pop_back();
            }
            return line;
        }
        return {};
    }

    uint64_t Skin::files_stamp() const
    {
        if (m_name.empty())
        {
            return 0;
        }
        const fs::path base = m_folder / path_from_utf8(m_name);
        uint64_t h = 1469598103934665603ull;
        auto mix = [&](const fs::path& p) {
            std::error_code ec;
            const auto t = fs::last_write_time(p, ec);
            const uint64_t stamp = ec ? 0 : static_cast<uint64_t>(t.time_since_epoch().count());
            const uint64_t size = ec ? 0 : static_cast<uint64_t>(fs::file_size(p, ec));
            h = (h ^ stamp) * 1099511628211ull;
            h = (h ^ size) * 1099511628211ull;
        };
        mix(base / "skin.json");
        std::set<std::string> files;
        for (const auto& [key, img] : m_spec.images)
        {
            files.insert(img.file);
        }
        if (!m_spec.font.empty())
        {
            files.insert(m_spec.font);
        }
        for (const std::string& f : files)
        {
            mix(base / path_from_utf8(f));
        }
        return h;
    }

    void Skin::clear_textures()
    {
        for (ImTextureData* t : m_textures)
        {
            if (t->Status == ImTextureStatus_WantCreate || t->Status == ImTextureStatus_Destroyed)
            {
                ImGui::UnregisterUserTexture(t); // never reached the backend
                IM_DELETE(t);
                continue;
            }
            t->SetStatus(ImTextureStatus_WantDestroy);
            t->UnusedFrames = 1; // backends destroy a texture once it has gone unused for a frame
            m_retired.push_back(t);
        }
        m_textures.clear();
        m_images.clear();
    }

    void Skin::drop_font()
    {
        if (m_font && ImGui::GetCurrentContext())
        {
            ImGui::GetIO().Fonts->RemoveFont(m_font);
        }
        m_font = nullptr;
    }

    void Skin::load_font(const fs::path& file)
    {
        std::ifstream in(file, std::ios::binary);
        if (!in)
        {
            m_problems.push_back("font: file not found");
            return;
        }
        std::vector<char> bytes((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        if (bytes.size() < 12 || bytes.size() > (32u << 20))
        {
            m_problems.push_back("font: not a usable TTF/OTF file");
            return;
        }
        const unsigned char* b = reinterpret_cast<const unsigned char*>(bytes.data());
        const bool ttf = (b[0] == 0 && b[1] == 1 && b[2] == 0 && b[3] == 0) || std::memcmp(b, "OTTO", 4) == 0 || std::memcmp(b, "true", 4) == 0 ||
                         std::memcmp(b, "ttcf", 4) == 0;
        if (!ttf)
        {
            m_problems.push_back("font: not a TTF/OTF file");
            return;
        }
        ImGuiIO& io = ImGui::GetIO();
        void* data = IM_ALLOC(bytes.size());
        std::memcpy(data, bytes.data(), bytes.size());
        ImFontConfig cfg;
        cfg.FontDataOwnedByAtlas = true;
        const float size = io.Fonts->Fonts.Size > 0 ? io.Fonts->Fonts[0]->LegacySize : 19.0f;
        m_font = io.Fonts->AddFontFromMemoryTTF(data, static_cast<int>(bytes.size()), size, &cfg);
        if (!m_font)
        {
            m_problems.push_back("font: could not be loaded");
        }
        else
        {
            // Skin fonts rarely contain Chinese glyphs: merge a CJK fallback into this font so
            // text drawn with it (PushFont(sk.font())) can show the Chinese translation.
            uuepbs::ui::merge_cjk_fallback(size);
        }
    }

    bool Skin::load(const std::string& requested, std::string& message)
    {
        const bool builtin = requested.empty() || lower(requested) == lower(kBuiltinName);
        if (builtin)
        {
            clear_textures();
            drop_font();
            m_spec = {};
            m_name.clear();
            m_display = kBuiltinName;
            m_problems.clear();
            m_status = "built-in look";
            m_stamp = 0;
            resolve_roles();
            m_style_dirty = true;
            message = "Window skin: " + m_display;
            std::lock_guard guard(g_request_lock);
            g_active = kBuiltinName;
            return true;
        }

        // Match the folder name case-insensitively ("ubs skin rose glass").
        std::string name = requested;
        for (const std::string& n : available())
        {
            if (lower(n) == lower(requested))
            {
                name = n;
            }
        }
        const fs::path base = m_folder / path_from_utf8(name);
        std::string text;
        {
            std::ifstream in(base / "skin.json", std::ios::binary);
            if (!in)
            {
                message = "Skin '" + requested + "' was not found in " + path_to_utf8(m_folder);
                m_status = message;
                return false;
            }
            std::ostringstream ss;
            ss << in.rdbuf();
            text = ss.str();
        }
        SkinSpec spec;
        std::vector<std::string> warnings;
        std::string why;
        if (!parse_skin(text, spec, why, &warnings))
        {
            message = "Skin '" + name + "' not loaded: " + why;
            m_status = message;
            m_stamp = 0; // keep the current look; retry when the file changes
            return false;
        }

        clear_textures();
        drop_font();
        m_spec = std::move(spec);
        m_name = name;
        m_display = m_spec.name.empty() ? name : m_spec.name;
        m_problems = std::move(warnings);

        // Decode every file once, even when several keys share it.
        std::map<std::string, std::pair<ImTextureData*, ImVec2>> by_file;
        size_t loaded = 0;
        for (const auto& [key, spec_img] : m_spec.images)
        {
            auto it = by_file.find(spec_img.file);
            if (it == by_file.end())
            {
                Rgba8Image img;
                std::string error;
                ImTextureData* tex = nullptr;
                ImVec2 size{};
                if (decode_image_file(base / path_from_utf8(spec_img.file), img, error))
                {
                    shrink_to_fit(img, kMaxTextureSide);
                    bleed_transparent_edges(img);
                    tex = make_texture(img);
                    m_textures.push_back(tex);
                    size = ImVec2(static_cast<float>(img.width), static_cast<float>(img.height));
                    ++loaded;
                }
                else
                {
                    m_problems.push_back(spec_img.file + ": " + error);
                }
                it = by_file.emplace(spec_img.file, std::make_pair(tex, size)).first;
            }
            if (!it->second.first)
            {
                continue;
            }
            Image image;
            image.spec = spec_img;
            image.tex = it->second.first;
            image.width = static_cast<int>(it->second.second.x);
            image.height = static_cast<int>(it->second.second.y);
            if (image.spec.mode == ImageMode::Nine && image.spec.slice[0] + image.spec.slice[1] + image.spec.slice[2] + image.spec.slice[3] <= 0.0f)
            {
                const float s = std::floor(static_cast<float>(std::min(image.width, image.height)) / 3.0f);
                image.spec.slice[0] = image.spec.slice[1] = image.spec.slice[2] = image.spec.slice[3] = s;
            }
            m_images.emplace(key, image);
        }
        if (!m_spec.font.empty())
        {
            load_font(base / path_from_utf8(m_spec.font));
        }
        resolve_roles();
        m_stamp = files_stamp();
        m_style_dirty = true;
        m_status = "'" + m_display + "'" + (m_spec.author.empty() ? "" : " by " + m_spec.author) + ", " + std::to_string(loaded) + " image(s)";
        if (!m_problems.empty())
        {
            m_status += ", " + std::to_string(m_problems.size()) + " problem(s)";
        }
        message = "Window skin: " + m_status;
        std::lock_guard guard(g_request_lock);
        g_active = m_name;
        return true;
    }

    bool Skin::update()
    {
        bool changed = false;
        std::optional<std::pair<std::string, bool>> req;
        {
            std::lock_guard guard(g_request_lock);
            req.swap(g_request);
        }
        if (req)
        {
            std::string message;
            if (load(req->first, message) && req->second)
            {
                remember(m_name);
            }
            changed = true;
        }

        // Reload the active skin when its files change (skin authors see edits right away).
        const double now = std::chrono::duration<double>(std::chrono::steady_clock::now().time_since_epoch()).count();
        if (!m_name.empty() && now >= m_next_check)
        {
            m_next_check = now + 1.0;
            const uint64_t stamp = files_stamp();
            if (stamp != m_stamp)
            {
                std::string message;
                load(m_name, message);
                m_stamp = stamp;
                changed = true;
            }
        }

        // Replaced textures: free them once the backend has let go.
        for (auto it = m_retired.begin(); it != m_retired.end();)
        {
            ImTextureData* t = *it;
            if (t->Status == ImTextureStatus_Destroyed)
            {
                ImGui::UnregisterUserTexture(t);
                IM_DELETE(t);
                it = m_retired.erase(it);
            }
            else
            {
                ++it;
            }
        }

        if (m_style_dirty)
        {
            m_style_dirty = false;
            changed = true;
        }
        return changed;
    }

    void Skin::shutdown()
    {
        for (ImTextureData* t : m_textures)
        {
            ImGui::UnregisterUserTexture(t);
            IM_DELETE(t);
        }
        for (ImTextureData* t : m_retired)
        {
            ImGui::UnregisterUserTexture(t);
            IM_DELETE(t);
        }
        m_textures.clear();
        m_retired.clear();
        m_images.clear();
        m_font = nullptr; // owned by the font atlas, which goes with the context
        m_split.ClearFreeMemory();
    }

