    bool parse_color(std::string_view text, ImVec4& out)
    {
        std::string_view s = text;
        while (!s.empty() && s.front() == ' ')
            s.remove_prefix(1);
        while (!s.empty() && s.back() == ' ')
            s.remove_suffix(1);
        if (s.empty() || s.front() != '#')
        {
            return false;
        }
        s.remove_prefix(1);
        int v[8];
        for (size_t i = 0; i < s.size(); ++i)
        {
            if (i >= 8 || (v[i] = hex_digit(s[i])) < 0)
            {
                return false;
            }
        }
        float c[4] = {0, 0, 0, 1};
        if (s.size() == 3 || s.size() == 4)
        {
            for (size_t i = 0; i < s.size(); ++i)
            {
                c[i] = static_cast<float>(v[i] * 17) / 255.0f;
            }
        }
        else if (s.size() == 6 || s.size() == 8)
        {
            for (size_t i = 0; i < s.size() / 2; ++i)
            {
                c[i] = static_cast<float>(v[i * 2] * 16 + v[i * 2 + 1]) / 255.0f;
            }
        }
        else
        {
            return false;
        }
        out = ImVec4(c[0], c[1], c[2], c[3]);
        return true;
    }

    bool parse_skin(const std::string& text, SkinSpec& out, std::string& message, std::vector<std::string>* warnings)
    {
        out = {};
        JsonValue root;
        if (!JsonReader(text).read(root, message))
        {
            message = "skin.json is not valid JSON: " + message;
            return false;
        }
        if (root.kind != JsonValue::Kind::Object)
        {
            message = "skin.json must be a JSON object { ... }";
            return false;
        }
        auto warn = [&](const std::string& w) {
            if (warnings)
            {
                warnings->push_back(w);
            }
        };
        auto text_of = [&](const char* key) {
            const JsonValue* v = root.find(key);
            return v && v->kind == JsonValue::Kind::String ? v->text : std::string();
        };
        out.name = text_of("name");
        out.author = text_of("author");
        out.description = text_of("description");
        out.font = text_of("font");

        if (const JsonValue* colors = root.find("colors"); colors && colors->kind == JsonValue::Kind::Object)
        {
            for (const auto& [key, v] : colors->members)
            {
                const std::string k = lower(key);
                const bool known = std::any_of(std::begin(kColorSlots), std::end(kColorSlots), [&](const ColorSlot& s) { return k == s.key; });
                ImVec4 c;
                if (!known)
                {
                    warn("colors: unknown key \"" + key + "\"");
                }
                else if (!color_of(v, c))
                {
                    warn("colors: \"" + key + "\" is not a colour like \"#E870A8\"");
                }
                else
                {
                    out.colors[k] = c;
                }
            }
        }
        if (const JsonValue* raw = root.find("imgui"); raw && raw->kind == JsonValue::Kind::Object)
        {
            for (const auto& [key, v] : raw->members)
            {
                ImVec4 c;
                if (color_of(v, c))
                {
                    out.imgui_colors[lower(key)] = c;
                }
                else
                {
                    warn("imgui: \"" + key + "\" is not a colour");
                }
            }
        }
        if (const JsonValue* style = root.find("style"); style && style->kind == JsonValue::Kind::Object)
        {
            for (const auto& [key, v] : style->members)
            {
                const std::string k = lower(key);
                const bool known = std::any_of(std::begin(kStyleSlots), std::end(kStyleSlots), [&](const StyleSlot& s) { return k == s.key; }) ||
                                   std::any_of(std::begin(kExtraStyleKeys), std::end(kExtraStyleKeys), [&](const char* s) { return k == s; });
                if (!known)
                {
                    warn("style: unknown key \"" + key + "\"");
                    continue;
                }
                if (v.kind == JsonValue::Kind::Number)
                {
                    out.style[k] = ImVec2(static_cast<float>(v.number), static_cast<float>(v.number));
                }
                else if (v.kind == JsonValue::Kind::Array && v.items.size() == 2 && v.items[0].kind == JsonValue::Kind::Number &&
                         v.items[1].kind == JsonValue::Kind::Number)
                {
                    out.style[k] = ImVec2(static_cast<float>(v.items[0].number), static_cast<float>(v.items[1].number));
                }
                else
                {
                    warn("style: \"" + key + "\" must be a number or [x, y]");
                }
            }
        }
        auto read_images = [&](const JsonValue* section, const char* prefix, bool icons) {
            if (!section)
            {
                return;
            }
            if (section->kind != JsonValue::Kind::Object)
            {
                warn(std::string(icons ? "icons" : "images") + " must be an object { ... }");
                return;
            }
            for (const auto& [key, v] : section->members)
            {
                const std::string k = std::string(prefix) + lower(key);
                if (!icons && !known_image_key(k))
                {
                    warn("images: unknown key \"" + key + "\"");
                    continue;
                }
                SkinImageSpec img;
                std::string why;
                if (!image_of(v, img, why))
                {
                    warn(std::string(icons ? "icons" : "images") + ": \"" + key + "\" " + why);
                    continue;
                }
                if (!safe_relative(img.file))
                {
                    warn(std::string(icons ? "icons" : "images") + ": \"" + key + "\" must name a file inside the skin folder");
                    continue;
                }
                if (!img.has_mode)
                {
                    img.mode = default_mode(k);
                }
                out.images[k] = img;
            }
        };
        read_images(root.find("images"), "", false);
        read_images(root.find("icons"), "icon.", true);
        message = "ok";
        return true;
    }

