"""Write src/character/npc_boss_effects.generated.h: the game's battle effects (Niagara systems under
PBZVFXPack/VFX/BattleFX) by folder, for the BOSS 特效 node.

Input: a package index of the game's IoStore container (a JSON list of {"path": ...}, as the local pak reader
writes it). Only package paths are read; no asset content. Run after a game update:
    python scripts/gen_boss_effects.py <iostore_index.json>
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src' / 'character' / 'npc_boss_effects.generated.h'
PREFIX = '../../../ProjectPBZ/Plugins/PBZVFXPack/Content/VFX/BattleFX/'
NAME = re.compile(r'^NS_[A-Za-z0-9_]+$')


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    index = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
    rows = {}
    for entry in index:
        path = entry['path']
        if not path.startswith(PREFIX) or not path.endswith('.uasset'):
            continue
        rel = path[len(PREFIX):-len('.uasset')]
        parts = rel.split('/')
        name = parts[-1]
        if len(parts) < 2 or not NAME.match(name) or not re.match(r'^[A-Za-z0-9_]+$', parts[0]):
            continue
        if name in rows:  # names are the node's key: keep the first
            continue
        rows[name] = (parts[0], '/PBZVFXPack/VFX/BattleFX/' + rel + '.' + name)
    ordered = sorted(rows.items(), key=lambda kv: (kv[1][0].lower(), kv[0].lower()))
    lines = [
        '// Generated by scripts/gen_boss_effects.py from the game\'s package index: do not edit.',
        '// The battle effects (Niagara systems) under PBZVFXPack/VFX/BattleFX, by folder (a boss, or Common / Weapon /',
        '// ShachiWeapon), sorted by folder then name. name: the node\'s key; path: the object path to load.',
        '#pragma once',
        'struct NpcBossEffect { const char* folder; const char* name; const char* path; };',
        'inline constexpr NpcBossEffect kNpcBossEffects[] = {',
    ]
    for name, (folder, path) in ordered:
        lines.append(f'    {{"{folder}", "{name}", "{path}"}},')
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    folders = len({f for f, _ in rows.values()})
    print(f'{len(ordered)} effects in {folders} folders -> {OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
